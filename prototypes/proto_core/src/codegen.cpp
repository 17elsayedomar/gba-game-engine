namespace proto {

std::string toIdentifier(const std::string& name) {
    std::string out;
    bool lastWasUnderscore = false;
    for (unsigned char ch : name) {
        if (std::isalnum(ch)) {
            out += static_cast<char>(std::tolower(ch));
            lastWasUnderscore = false;
        } else if (!lastWasUnderscore && !out.empty()) {
            out += '_';  // spaces and symbols become a single underscore
            lastWasUnderscore = true;
        }
    }
    while (!out.empty() && out.back() == '_') out.pop_back();
    if (out.empty()) out = "unnamed";
    if (std::isdigit(static_cast<unsigned char>(out[0]))) out = "n_" + out;  // can't start with a digit
    return out;
}

// Gives every object a unique identifier. If two objects are both called "Coin",
// they become coin and coin_2. Objects are processed in Hierarchy order, so the
// result never changes unless the scene changes.
static std::map<ObjectId, std::string> uniqueObjectIdentifiers(const Scene& scene) {
    std::map<ObjectId, std::string> result;
    std::set<std::string> used;
    for (const GameObject& object : scene.objects) {
        std::string base = toIdentifier(object.name);
        std::string candidate = base;
        for (int n = 2; used.count(candidate); ++n) candidate = base + "_" + std::to_string(n);
        used.insert(candidate);
        result[object.id] = candidate;
    }
    return result;
}

// A banner comment line padded with dashes to a fixed width, e.g.
// "// --- GameObject "Player" ------------------------------------------------"
static std::string sectionLine(const std::string& title) {
    std::string line = "// --- " + title + " ";
    while (line.size() < 78) line += '-';
    return line;
}

std::string generateSceneSource(const Scene& scene) {
    std::ostringstream out;
    const std::string sceneId = toIdentifier(scene.name);
    const auto objectIds = uniqueObjectIdentifiers(scene);

    out << "// ============================================================================\n"
        << "// gen_scene_" << sceneId << ".cpp\n"
        << "// GENERATED by GBA Game Engine from scene \"" << scene.name << "\". Do not edit:\n"
        << "// this file is rewritten on every build. Change the scene in the editor, or\n"
        << "// put your own code in the scripts/ folder instead.\n"
        << "// ============================================================================\n\n"
        << "// The engine runtime: sprite drawing, scene loading, hardware setup.\n"
        << "#include \"gbe/runtime.hpp\"\n\n";

    // --- Assets that are actually used by at least one object ---
    std::set<AssetId> usedAssets;
    for (const GameObject& object : scene.objects) {
        if (const Component* sprite = object.findComponent(sprite_renderer::kType)) {
            if (sprite->values[sprite_renderer::kSprite] != 0)
                usedAssets.insert(sprite->values[sprite_renderer::kSprite]);
        }
    }
    if (!usedAssets.empty()) {
        out << sectionLine("Sprite assets") << "\n"
            << "// Pixel data lives in gen_assets.cpp, converted from the original PNG\n"
            << "// files into the GBA's tile format at build time.\n";
        for (const Asset& asset : scene.assets) {
            if (!usedAssets.count(asset.id)) continue;
            out << "// \"" << asset.name << "\": " << asset.original.width << "x"
                << asset.original.height << " pixels, " << asset.gbaColorCount << " colors ("
                << (asset.gbaColorCount <= 15 ? "fits a 16-color palette bank" : "needs 256-color mode")
                << ").\n"
                << "extern const gbe::SpriteAsset gen_asset_" << toIdentifier(asset.name) << ";\n";
        }
        out << "\n";
    }

    // --- One block per GameObject ---
    for (const GameObject& object : scene.objects) {
        const std::string& ident = objectIds.at(object.id);
        out << sectionLine("GameObject \"" + object.name + "\"") << "\n"
            << "// Starts at pixel (" << object.x << ", " << object.y << "). The GBA screen is\n"
            << "// 240x160 pixels with (0, 0) in the top-left corner. Draw order z = " << object.z
            << ".\n";
        for (const Component& component : object.components) {
            const ComponentDescriptor* descriptor = findComponentDescriptor(component.type);
            if (!descriptor) continue;
            if (component.type == sprite_renderer::kType) {
                const Asset* asset = scene.findAsset(component.values[sprite_renderer::kSprite]);
                out << "// Sprite Renderer: shows "
                    << (asset ? "\"" + asset->name + "\"" : std::string("no sprite yet"))
                    << " with OBJ priority " << component.values[sprite_renderer::kPriority]
                    << " (0 = in front of all backgrounds).\n";
            } else {
                out << "// " << descriptor->displayName << ":";
                for (size_t i = 0; i < descriptor->properties.size(); ++i) {
                    out << " " << descriptor->properties[i].name << " = " << component.values[i]
                        << (i + 1 < descriptor->properties.size() ? "," : ".");
                }
                out << "\n";
            }
        }
        out << "static const gbe::ObjectInit gen_obj_" << ident << " = {\n"
            << "    .x = " << object.x << ", .y = " << object.y << ", .z = " << object.z << ",\n";
        if (const Component* sprite = object.findComponent(sprite_renderer::kType)) {
            const Asset* asset = scene.findAsset(sprite->values[sprite_renderer::kSprite]);
            out << "    .sprite = " << (asset ? "&gen_asset_" + toIdentifier(asset->name) : "nullptr")
                << ", .priority = " << sprite->values[sprite_renderer::kPriority] << ",\n";
        }
        out << "};\n\n";
    }

    // --- The list the runtime walks when the scene starts ---
    out << sectionLine("Scene object list") << "\n"
        << "// The runtime creates these objects, in this order, when the scene starts.\n"
        << "const gbe::ObjectInit* const gen_scene_" << sceneId << "_objects[] = {\n";
    for (const GameObject& object : scene.objects) {
        out << "    &gen_obj_" << objectIds.at(object.id) << ",\n";
    }
    if (scene.objects.empty()) out << "    nullptr,  // (the scene has no objects yet)\n";
    out << "};\n";
    return out.str();
}

}  // namespace proto
